"""Build the H2 demo schema from the project's canonical MySQL table definitions."""

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "sql" / "personal_health_with_risk.sql"
DISEASE_SOURCE = ROOT / "chronic-disease" / "sql" / "disease_risk_upgrade_mysql.sql"
TARGET = ROOT / "IHMS-admin" / "src" / "main" / "resources" / "demo" / "schema.sql"


def convert_table(statement: str) -> str:
    body = re.sub(r"\)\s*ENGINE\s*=\s*InnoDB.*;\s*$", ");", statement, flags=re.I | re.S)
    if body == statement:
        raise ValueError("Cannot locate MySQL table options")
    lines = []
    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith(("INDEX ", "KEY ")):
            continue  # The small demo dataset does not need secondary indexes.
        line = re.sub(r"\s+CHARACTER SET\s+\w+\s+COLLATE\s+\w+", "", line, flags=re.I)
        line = re.sub(r"\s+COMMENT\s+'[^']*'", "", line, flags=re.I)
        line = re.sub(r"\s+USING BTREE", "", line, flags=re.I)
        line = re.sub(r"\s+UNSIGNED", "", line, flags=re.I)
        line = re.sub(r"\s+ON UPDATE CURRENT_TIMESTAMP", "", line, flags=re.I)
        line = re.sub(r"\bTINYINT\(1\)", "TINYINT", line, flags=re.I)
        line = re.sub(r"\bLONGTEXT\b", "CLOB", line, flags=re.I)
        line = re.sub(r"\bTEXT\b", "CLOB", line, flags=re.I)
        line = re.sub(r"\bDATETIME\b", "TIMESTAMP", line, flags=re.I)
        lines.append(line)
    for index in range(len(lines) - 2, 0, -1):
        if lines[index].strip():
            lines[index] = lines[index].rstrip().rstrip(",")
            break
    return re.sub(r"^CREATE TABLE (?!IF NOT EXISTS)", "CREATE TABLE IF NOT EXISTS ",
                  "\n".join(lines))


def main() -> None:
    data_path = TARGET.parent / 'data.sql'
    data = data_path.read_text(encoding='utf-8').split('-- Adult resting reference defaults.')[0].rstrip()
    data_path.write_text(data + '\n\n-- Adult resting reference defaults.\n'
                         + (ROOT / 'sql' / 'health_reference_defaults.sql').read_text(encoding='utf-8'), encoding='utf-8')
    source = SOURCE.read_text(encoding="utf-8-sig")
    tables = re.findall(r"(?ms)^CREATE TABLE (?:IF NOT EXISTS )?`[^`]+`\s*\(.*?;", source)
    if len(tables) != 20:
        raise ValueError(f"Expected 20 tables, found {len(tables)}")
    disease_tables = re.findall(r"(?ms)^CREATE TABLE IF NOT EXISTS \w+\s*\(.*?;",
                                DISEASE_SOURCE.read_text(encoding="utf-8-sig"))
    if len(disease_tables) != 4:
        raise ValueError(f"Expected 4 disease tables, found {len(disease_tables)}")
    tables.extend(disease_tables)
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(
        "-- Generated by scripts/build_demo_schema.py; edit the MySQL schema instead.\n"
        "-- H2 runs in MySQL compatibility mode for this demo.\n\n"
        + "\n\n".join(convert_table(table) for table in tables)
        + "\n\n-- Upgrade existing H2 demo files without replacing user data.\n"
        + "ALTER TABLE `elder_vital_measurement` ADD COLUMN IF NOT EXISTS `respiratory_rate` DECIMAL(8,2) NULL;\n"
        + "ALTER TABLE `elder_vital_measurement` ADD COLUMN IF NOT EXISTS `supplemental_oxygen` TINYINT NULL;\n"
        + "ALTER TABLE `elder_vital_measurement` ADD COLUMN IF NOT EXISTS `consciousness` VARCHAR(24) NULL;\n"
        + "ALTER TABLE `personalized_risk_assessment` ADD COLUMN IF NOT EXISTS `single_alerts_json` CLOB NULL;\n"
        + "ALTER TABLE `personalized_risk_assessment` ADD COLUMN IF NOT EXISTS `news2_complete` TINYINT NOT NULL DEFAULT 0;\n"
        + "ALTER TABLE `personalized_risk_assessment` ADD COLUMN IF NOT EXISTS `assessment_basis` VARCHAR(32) NOT NULL DEFAULT 'LEGACY';\n"
        + "ALTER TABLE `personalized_risk_assessment` ADD COLUMN IF NOT EXISTS `request_id` VARCHAR(36) NULL;\n"
        + "ALTER TABLE `personalized_risk_assessment` ADD COLUMN IF NOT EXISTS `input_snapshot_json` CLOB NULL;\n"
        + "CREATE UNIQUE INDEX IF NOT EXISTS `uk_personal_assessment_request` ON `personalized_risk_assessment` (`user_id`,`request_id`);\n"
        + "\n-- Measurement rule alerts (phase 2).\n"
        + alert_schema()
        + "\n-- Health notifications (phase 3).\n"
        + notification_schema()
        + "\n-- SOS (phase 4), additive upgrade of existing demo files.\n"
        + sos_schema(),
        encoding="utf-8",
        newline="\n",
    )


def alert_schema() -> str:
    source = (ROOT / "sql" / "health_alert_upgrade_mysql.sql").read_text(encoding="utf-8")
    tables = re.findall(r"(?ms)^CREATE TABLE IF NOT EXISTS \w+\s*\(.*?;", source)
    seeds = source[source.index("-- Stable numeric"):]
    return "\n\n".join(convert_table(table) for table in tables) + "\n\n" + seeds


def notification_schema() -> str:
    source = (ROOT / "sql" / "health_notification_upgrade_mysql.sql").read_text(encoding="utf-8")
    tables = re.findall(r"(?ms)^CREATE TABLE IF NOT EXISTS \w+\s*\(.*?;", source)
    return ("\n\n".join(convert_table(table) for table in tables) + "\n"
            + "ALTER TABLE health_notification_task ADD COLUMN IF NOT EXISTS priority INT NOT NULL DEFAULT 0;\n")


def sos_schema() -> str:
    source = (ROOT / "sql" / "health_sos_upgrade_mysql.sql").read_text(encoding="utf-8")
    tables = re.findall(r"(?ms)^CREATE TABLE IF NOT EXISTS \w+\s*\(.*?;", source)
    return ("ALTER TABLE health_alert_event ALTER COLUMN first_measurement_id DROP NOT NULL;\n"
            "ALTER TABLE health_alert_event ALTER COLUMN last_measurement_id DROP NOT NULL;\n"
            "ALTER TABLE health_notification_task ALTER COLUMN measurement_id DROP NOT NULL;\n"
            "ALTER TABLE health_notification_task ADD COLUMN IF NOT EXISTS priority INT NOT NULL DEFAULT 0;\n"
            + "\n\n".join(convert_table(table) for table in tables) + "\n")


if __name__ == "__main__":
    main()
